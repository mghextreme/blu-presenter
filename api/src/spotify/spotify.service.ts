import {
  BadRequestException,
  ForbiddenException,
  HttpException,
  Injectable,
  NotFoundException,
  Scope,
} from '@nestjs/common';
import { getSpotifyTrackId } from 'src/utils/spotify';
import {
  PlaylistAccountProfile,
  PlaylistIntegrationService,
} from 'src/playlist-integration/playlist-integration.service';

const SPOTIFY_ACCOUNTS_BASE = 'https://accounts.spotify.com';
const SPOTIFY_API_BASE = 'https://api.spotify.com/v1';

/** Spotify accepts up to 100 items per playlist write request. */
const TRACKS_PER_REQUEST = 100;

/** Creates and syncs schedule playlists on the user's Spotify account. */
@Injectable({ scope: Scope.REQUEST })
export class SpotifyService extends PlaylistIntegrationService {
  protected readonly provider = 'spotify';
  protected readonly source = 'spotify-auto';
  protected readonly serviceName = 'Spotify';
  protected readonly authorizeUrl = `${SPOTIFY_ACCOUNTS_BASE}/authorize`;
  protected readonly tokenUrl = `${SPOTIFY_ACCOUNTS_BASE}/api/token`;
  protected readonly apiBase = SPOTIFY_API_BASE;
  protected readonly connectScopes = [
    'user-read-email',
    'user-read-private',
    'playlist-modify-private',
    'playlist-modify-public',
  ];

  protected extraAuthorizeParams(): Record<string, string> {
    return { show_dialog: 'false' };
  }

  protected getItemId(url: string): string | null {
    return getSpotifyTrackId(url);
  }

  protected async fetchAccountProfile(
    accessToken: string,
  ): Promise<PlaylistAccountProfile> {
    const response = await fetch(`${SPOTIFY_API_BASE}/me`, {
      headers: { Authorization: `Bearer ${accessToken}` },
    });

    if (!response.ok) {
      throw new BadRequestException('Failed to fetch Spotify profile');
    }

    const profile = (await response.json()) as {
      id: string;
      display_name: string | null;
    };
    return { id: profile.id, displayName: profile.display_name ?? null };
  }

  protected async createPlaylist(
    name: string,
    isPublic: boolean,
  ): Promise<string> {
    const playlist = await this.apiRequest<{
      id: string;
      external_urls: { spotify: string };
    }>('/me/playlists', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        name,
        public: isPublic,
        description: 'Generated by BluPresenter',
      }),
    });

    return (
      playlist.external_urls?.spotify ??
      `https://open.spotify.com/playlist/${playlist.id}`
    );
  }

  /**
   * Replaces all tracks of the playlist while keeping its id (so followers
   * and saved copies are preserved).
   */
  protected async writePlaylistItems(
    playlistUrl: string,
    trackIds: string[],
  ): Promise<string[]> {
    const playlistId = this.extractPlaylistId(playlistUrl);
    const path = `/playlists/${encodeURIComponent(playlistId)}/items`;
    const trackUris = trackIds.map((id) => `spotify:track:${id}`);

    // The first request replaces the playlist contents, the rest append.
    await this.apiRequest(path, {
      method: 'PUT',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ uris: trackUris.slice(0, TRACKS_PER_REQUEST) }),
    });

    for (
      let i = TRACKS_PER_REQUEST;
      i < trackUris.length;
      i += TRACKS_PER_REQUEST
    ) {
      await this.apiRequest(path, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          uris: trackUris.slice(i, i + TRACKS_PER_REQUEST),
        }),
      });
    }

    return [];
  }

  private extractPlaylistId(url: string): string {
    try {
      const parsed = new URL(url);
      const match = /\/playlist\/([a-zA-Z0-9]+)/.exec(parsed.pathname);
      if (parsed.hostname !== 'open.spotify.com' || !match) {
        throw new Error('Not a Spotify playlist URL');
      }
      return match[1];
    } catch {
      throw new BadRequestException('Invalid Spotify playlist URL');
    }
  }

  protected toApiException(status: number, body: string): HttpException {
    let spMessage = body;
    try {
      spMessage = JSON.parse(body)?.error?.message ?? body;
    } catch {
      // keep raw body as the message
    }

    if (status === 404) {
      return new NotFoundException(
        'The Spotify playlist no longer exists. Remove the playlist reference to generate a new one.',
      );
    }
    if (status === 403) {
      return new ForbiddenException(
        `Spotify rejected the request: ${spMessage}`,
      );
    }
    return new BadRequestException(`Spotify API error: ${spMessage}`);
  }
}
