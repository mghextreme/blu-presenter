import {
  BadRequestException,
  ForbiddenException,
  HttpException,
  HttpStatus,
  Injectable,
  NotFoundException,
} from '@nestjs/common';
import { IPlaylistConnection } from 'src/types';
import { getYouTubePlaylistId, getYouTubeVideoId } from 'src/utils/youtube';
import {
  PlaylistAccountProfile,
  PlaylistIntegrationService,
  PlaylistUserContext,
} from 'src/playlist-integration/playlist-integration.service';
import { fetchWithTimeout } from 'src/utils/fetch-with-timeout';

const GOOGLE_AUTHORIZE_URL = 'https://accounts.google.com/o/oauth2/v2/auth';
const GOOGLE_TOKEN_URL = 'https://oauth2.googleapis.com/token';
const GOOGLE_REVOKE_URL = 'https://oauth2.googleapis.com/revoke';
const YOUTUBE_API_BASE = 'https://www.googleapis.com/youtube/v3';

/** YouTube rejects playlist titles longer than this. */
const MAX_PLAYLIST_TITLE_LENGTH = 150;
const ITEMS_PER_PAGE = 50;
/** Waits before retrying the first insert into a just-created playlist. */
const NEW_PLAYLIST_RETRY_DELAYS_MS = [1000, 2000, 4000];

interface PlaylistItem {
  /** The playlist item id (needed to delete it). */
  id: string;
  videoId: string;
}

/** An insert refused because the video doesn't exist (anymore). */
class YouTubeVideoNotFoundException extends NotFoundException {}

/**
 * Creates and syncs schedule playlists on the user's YouTube channel.
 *
 * YouTube has no bulk "replace playlist items" call, and every insert or
 * delete costs 50 units of a daily API quota (10,000 by default), so syncs
 * only rewrite what changed: the items matching the schedule's start are
 * kept, everything after the first difference is replaced.
 */
@Injectable()
export class YoutubeService extends PlaylistIntegrationService {
  protected readonly provider = 'youtube';
  protected readonly source = 'youtube-auto';
  protected readonly serviceName = 'YouTube';
  protected readonly authorizeUrl = GOOGLE_AUTHORIZE_URL;
  protected readonly tokenUrl = GOOGLE_TOKEN_URL;
  protected readonly apiBase = YOUTUBE_API_BASE;
  protected readonly connectScopes = [
    'https://www.googleapis.com/auth/youtube',
  ];

  // Available to every user once YOUTUBE_CLIENT_ID/SECRET are set.
  protected get requiresOptIn(): boolean {
    return false;
  }

  protected extraAuthorizeParams(): Record<string, string> {
    // Google only issues a refresh token on offline access, and only on the
    // first consent unless the consent screen is shown again.
    return { access_type: 'offline', prompt: 'consent' };
  }

  protected getItemId(url: string): string | null {
    return getYouTubeVideoId(url);
  }

  protected async fetchAccountProfile(
    accessToken: string,
  ): Promise<PlaylistAccountProfile> {
    const response = await fetchWithTimeout(
      `${YOUTUBE_API_BASE}/channels?part=snippet&mine=true`,
      { headers: { Authorization: `Bearer ${accessToken}` } },
    );

    if (!response.ok) {
      throw new BadRequestException('Failed to fetch YouTube channel');
    }

    const data = (await response.json()) as {
      items?: { id: string; snippet?: { title?: string } }[];
    };
    const channel = data.items?.[0];
    if (!channel) {
      throw new BadRequestException(
        'This Google account has no YouTube channel. Create one on YouTube and try again.',
      );
    }

    return { id: channel.id, displayName: channel.snippet?.title ?? null };
  }

  protected async revokeToken(connection: IPlaylistConnection): Promise<void> {
    await fetchWithTimeout(GOOGLE_REVOKE_URL, {
      method: 'POST',
      headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
      body: new URLSearchParams({ token: connection.refreshToken! }),
    });
  }

  protected async createPlaylist(
    context: PlaylistUserContext,
    name: string,
    isPublic: boolean,
  ): Promise<string> {
    const playlist = await this.apiRequest<{ id: string }>(
      context,
      '/playlists?part=snippet,status',
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          snippet: {
            title: name.slice(0, MAX_PLAYLIST_TITLE_LENGTH),
            description: 'Generated by BluPresenter',
          },
          // Unlisted rather than private, so other members can open it.
          status: { privacyStatus: isPublic ? 'public' : 'unlisted' },
        }),
      },
    );

    return `https://www.youtube.com/playlist?list=${playlist.id}`;
  }

  protected async writePlaylistItems(
    context: PlaylistUserContext,
    playlistUrl: string,
    videoIds: string[],
    isNew: boolean,
  ): Promise<string[]> {
    const playlistId = this.extractPlaylistId(playlistUrl);
    // A playlist created moments ago is empty, and YouTube may still answer
    // 404 (playlistNotFound) for it while it propagates: skip the listing.
    const current = isNew
      ? []
      : await this.listPlaylistItems(context, playlistId);

    let keep = 0;
    while (
      keep < current.length &&
      keep < videoIds.length &&
      current[keep].videoId === videoIds[keep]
    ) {
      keep++;
    }

    for (const item of current.slice(keep)) {
      await this.apiRequest(
        context,
        `/playlistItems?id=${encodeURIComponent(item.id)}`,
        { method: 'DELETE' },
      );
    }

    // Inserts without a position append, so these land in order.
    const failed: string[] = [];
    // Only the first insert into a new playlist can race its propagation.
    let mayNotExistYet = isNew;
    for (const videoId of videoIds.slice(keep)) {
      try {
        await this.insertPlaylistItem(
          context,
          playlistId,
          videoId,
          mayNotExistYet,
        );
        mayNotExistYet = false;
      } catch (e) {
        if (!(e instanceof YouTubeVideoNotFoundException)) {
          throw e;
        }
        failed.push(videoId);
      }
    }

    return failed;
  }

  /**
   * Appends a video to the playlist. With `retryNotFound`, a 404 is retried
   * a few times with backoff, as a newly created playlist can take a few
   * seconds to become visible to the playlistItems endpoints.
   */
  private async insertPlaylistItem(
    context: PlaylistUserContext,
    playlistId: string,
    videoId: string,
    retryNotFound: boolean,
  ): Promise<void> {
    const delays = retryNotFound ? NEW_PLAYLIST_RETRY_DELAYS_MS : [];
    for (let attempt = 0; ; attempt++) {
      try {
        await this.apiRequest(context, '/playlistItems?part=snippet', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            snippet: {
              playlistId,
              resourceId: { kind: 'youtube#video', videoId },
            },
          }),
        });
        return;
      } catch (e) {
        if (!(e instanceof NotFoundException) || attempt >= delays.length) {
          throw e;
        }
        await this.sleep(delays[attempt]);
      }
    }
  }

  /** Separate so tests can skip the waits. */
  protected sleep(ms: number): Promise<void> {
    return new Promise((resolve) => setTimeout(resolve, ms));
  }

  private async listPlaylistItems(
    context: PlaylistUserContext,
    playlistId: string,
  ): Promise<PlaylistItem[]> {
    const items: PlaylistItem[] = [];
    let pageToken: string | undefined;

    do {
      const params = new URLSearchParams({
        part: 'contentDetails',
        playlistId,
        maxResults: String(ITEMS_PER_PAGE),
        fields: 'nextPageToken,items(id,contentDetails/videoId)',
      });
      if (pageToken) {
        params.set('pageToken', pageToken);
      }

      const page = await this.apiRequest<{
        nextPageToken?: string;
        items?: { id: string; contentDetails?: { videoId?: string } }[];
      }>(context, `/playlistItems?${params.toString()}`);

      for (const item of page.items ?? []) {
        items.push({
          id: item.id,
          videoId: item.contentDetails?.videoId ?? '',
        });
      }
      pageToken = page.nextPageToken;
    } while (pageToken);

    return items;
  }

  private extractPlaylistId(url: string): string {
    const playlistId = getYouTubePlaylistId(url);
    if (!playlistId) {
      throw new BadRequestException('Invalid YouTube playlist URL');
    }
    return playlistId;
  }

  protected toApiException(status: number, body: string): HttpException {
    let message = body;
    let reason: string | undefined;
    try {
      const error = JSON.parse(body)?.error;
      message = error?.message ?? body;
      reason = error?.errors?.[0]?.reason;
    } catch {
      // keep raw body as the message
    }

    switch (reason) {
      case 'quotaExceeded':
      case 'rateLimitExceeded':
      case 'userRateLimitExceeded':
        return new HttpException(
          'The YouTube API quota was exceeded. Please try again later.',
          HttpStatus.TOO_MANY_REQUESTS,
        );
      case 'videoNotFound':
        return new YouTubeVideoNotFoundException(message);
      case 'playlistNotFound':
        return new NotFoundException(
          'The YouTube playlist no longer exists. Remove the playlist reference to generate a new one.',
        );
      case 'youtubeSignupRequired':
        return new BadRequestException(
          'This Google account has no YouTube channel. Create one on YouTube and try again.',
        );
    }

    if (status === 404) {
      return new NotFoundException(
        'The YouTube playlist no longer exists. Remove the playlist reference to generate a new one.',
      );
    }
    if (status === 403) {
      return new ForbiddenException(`YouTube rejected the request: ${message}`);
    }
    return new BadRequestException(`YouTube API error: ${message}`);
  }
}
